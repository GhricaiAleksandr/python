# Импортируем модуль для работы со случайными числами
import random

def play_game():
    # 1. Загадываем случайное целое число от 1 до 100
    secret_number = random.randint(1, 100)
    
    # 2. Создаем переменную-счётчик попыток со значением 0
    attempts = 0
    
    # 3. Выводим приветственное сообщение и инструкцию по выходу из игры
    print("🤖 Я загадал число от 1 до 100. Попробуй угадать!")
    print("💡 Для выхода из игры в любой момент введите 'exit'.\n")

    # 4. Запускаем бесконечный цикл игры
    while True:
        # Считываем текст, который ввел пользователь
        user_input = input("Введите ваше число: ")

        # Проверяем: ввел ли пользователь команду выхода
        if user_input.lower() == 'exit':
            print("Игра завершена. До встречи!")
            break  # Выходим из цикла while

        # Проверяем: состоит ли строка только из цифр
        if not user_input.isdigit():
            print("⚠️ Пожалуйста, введите целое положительное число!")
            continue  # Возвращаемся к началу цикла

        # Переводим текстовую строку в целое математическое число
        guess = int(user_input)
        
        # Увеличиваем значение переменной-счётчика на 1
        attempts += 1

        # Сравниваем введенное число с загаданным
        if guess < secret_number:
            print("📉 Загаданное число БОЛЬШЕ!\n")
        elif guess > secret_number:
            print("📈 Загаданное число МЕНЬШЕ!\n")
        else:
            print(f"🎉 Поздравляю! Вы угадали число {secret_number} за {attempts} попыток!")
            break  # Число угадано — завершаем цикл

# Точка входа: запускает игру, если файл запущен напрямую
if __name__ == "__main__":
    play_game()


