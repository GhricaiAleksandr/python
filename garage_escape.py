def start_game():
    # Словарь состояния (флаги инвентаря)
    state = {
        "has_key": False,
        "has_crowbar": False
    }

    print("🚪 Вы очнулись в закрытом гараже. Вокруг полумрак.")
    print("Доступные объекты: верстак, стеллаж, ворота.")
    print("💡 Для выхода из игры введите 'exit'.\n")

    while True:
        action = input("Что вы хотите осмотреть? (верстак / стеллаж / ворота): ").strip().lower()

        # Выход из игры
        if action == "exit":
            print("Вы сдались и остались в гараже. Игра завершена.")
            break

        # Взаимодействие с верстаком
        elif action == "верстак":
            print("\n🔧 Вы подошли к верстаку.")
            if state["has_key"]:
                print("Верстак пуст. Вы уже забрали отсюда ключи.")
            else:
                take_key = input("Вы нашли связку ключей! Взять ключи? (да / нет): ").strip().lower()
                if take_key == "да":
                    state["has_key"] = True
                    print("🔑 Вы взяли ключи и положили их в карман.")
                else:
                    print("Вы оставили ключи лежать на верстаке.")

        # Взаимодействие со стеллажом
        elif action == "стеллаж":
            print("\n📦 Вы осматриваете старый металлический стеллаж.")
            if state["has_crowbar"]:
                print("Стеллаж пуст. Вы уже забрали лом.")
            else:
                take_crowbar = input("На нижней полке лежит тяжелый лом. Взять лом? (да / нет): ").strip().lower()
                if take_crowbar == "да":
                    state["has_crowbar"] = True
                    print("🛠 Вы взяли лом.")
                else:
                    print("Вы решили не брать лом.")

        # Взаимодействие с воротами (условие победы/выхода)
        elif action == "ворота":
            print("\n🚪 Вы подошли к огромным металлическим воротам. Они заперты.")
            choice = input("Как попытаться открыть? (ключ / лом / отойти): ").strip().lower()

            if choice == "ключ":
                if state["has_key"]:
                    print("\n🎉 ВЫ ПОБЕДИЛИ! Ключ подошел к замку, ворота скрипнули и открылись! Вы на свободе!")
                    break
                else:
                    print("❌ У вас нет ключа! Сначала нужно его найти.")

            elif choice == "лом":
                if state["has_crowbar"]:
                    print("\n💥 ВЫ ПОБЕДИЛИ! Вы поддели замковую петлю ломом, сбили замок и вырвались на улицу!")
                    break
                else:
                    print("❌ У вас нет лома! Ищите инструмент на стеллаже.")

            elif choice == "отойти":
                print("Вы отошли от ворот обратно в центр гаража.")

            else:
                print("⚠️ Неизвестное действие с воротами.")

        # Некорректный ввод основного действия
        else:
            print("⚠️ Вы смотрите по сторонам, но такого объекта нет. Выберите: верстак, стеллаж или ворота.")

# Точка входа для запуска
if __name__ == "__main__":
    start_game()

