# 3. ЦИКЛ БЕСКОНЕЧНЫЙ (while True):
#     а. ЗАПРОСИТЬ user_input
#     б. ЕСЛИ user_input == 'exit' -> ВЫЙТИ (break)
#     в. ЕСЛИ user_input NOT IN options -> ОШИБКА, ПОВТОР (continue)
#     г. ВЫБРАТЬ computer_choice через random.choice(options)
#     д. СРАВНИТЬ:
#            - user_input == computer_choice -> НИЧЬЯ
#            - elif (победа игрока 1 or 2 or 3) -> ВЫИГРЫШ ИГРОКА
