# 💡 КЛЮЧЕВЫЕ НАВЫКИ И МОМЕНТЫ ЭТОГО ПРОЕКТА:
# 1. random.choice(options) — функция берет случайный элемент из переданного списка.
# 2. user_input not in options — быстрая проверка валидности ввода пользователем.
# 3. Группировка условий победы — конструкция elif (...) or (...) or (...) 
#    объединяет 3 сценария победы в один чистый блок.
# =====================================================================

import random

def play_game():
    # Создаем список (list) допустимых вариантов игры
    options = ["камень", "ножницы", "бумага"]
    
    print("🤖 Добро пожаловать в игру 'Камень, Ножницы, Бумага'!")
    print(" 💡 Для выхода из игры в любой момент введите 'exit'.\n")
    
    while True:
        # Считываем ввод пользователя, убираем пробелы и приводим к нижнему регистру
        user_input = input("Ваш ход (камень / ножницы / бумага): ").strip().lower()
        
        # Проверка команды выхода из игры
        if user_input == 'exit':
            print("Игра завершена. До встречи!")
            break
            
        # 💡 КЛЮЧЕВОЙ МОМЕНТ №2: быстрая проверка валидности ввода через 'not in'
        if user_input not in options:
            print(" ⚠️ Некорректный ввод! Пожалуйста, введите: камень, ножницы или бумага.\n")
            continue
            
        # 💡 КЛЮЧЕВОЙ МОМЕНТ №1: random.choice берет случайный элемент из списка options
        computer_choice = random.choice(options)
        print(f" 🤖 Компьютер выбрал: {computer_choice}")
        
        # Проверка исхода раунда
        if user_input == computer_choice:
            print(" 🤝 Ничья!\n")
            
        # 💡 КЛЮЧЕВОЙ МОМЕНТ №3: Группировка условий победы (3 сценария в одном чистом блоке)
        elif (user_input == "камень" and computer_choice == "ножницы") or \
             (user_input == "ножницы" and computer_choice == "бумага") or \
             (user_input == "бумага" and computer_choice == "камень"):
            print(" 🎉 Вы выиграли этот раунд!\n")
        else:
            print(" 💻 Компьютер выиграл этот раунд!\n")

# Точка входа для запуска игры
if __name__ == "__main__":
    play_game()

